# 딕셔너리 기초

# ===========================================================
#  딕셔너리 (dict): 키와 값 쌍으로 저장하는 변경 가능한 자료형
#  딕셔너리의 특징
#  1. ( mutable, 변경 가능 )
#  2. ( iterable, 반복 가능 )
#  3. ( sequence X,인덱싱과 슬라이싱 불가 )
#  4. ( 키는 중복 불가, 값은 중복 가능 )
# ===========================================================

# 딕셔너리 생성
a = {}
b = dict()
print(type(a), type(b))

d = {"id": 1306, "name": "박하늘", "age": 17}
print(d)

# 키로 값 가져오기
print(d["name"])


# 에러가 안나게 하려면?
if "phone" in d:
    print(d["phone"])
print(d.get("phone"))   # 없으면 디폴트값 출력. 현재 디폴트가 none이라none 리턴
print(d.get("phone", "전화없음"))   # 이러면 디폴트값: "전화없음"

# ===========================================================
# 1. 딕셔너리는 mutable하다. (변경 가능)
# ===========================================================
d["age"] += 1
print(d)

d["phone"] = "6313-0575" # 전번 추가
print(d)

del d["phone"] # 전번 삭제
print(d)

# ===========================================================
# 2. 딕셔너리는 iterable하다. (반복 가능)
# ===========================================================

# 딕셔너리 순회
for key in d:
    print(key, d[key])

for i, key in enumerate(d):
    print(i, key)

for value in d.values(): # 딕셔너리에서 값만 가져옴
    print(value)

for key, value in d.items(): # 아이텝: 키, 값 쌍
    print(key, value)
# ===========================================================
# 3. 딕셔너리는 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================
d[0] = "python" # 0이라는 키값이 생긴거임 인덱스 넣은 게 아니라



# ===========================================================
# 4. 딕셔너리는 키는 중복 불가, 값은 중복 가능하다.
# ===========================================================

d = {"kor": 90, "mat": 85, "eng": 80}

d["kor"] = 100
print(d)

d["sci"] = 80
print(d)

d[3.14] = 100
print(d)

d[True] = 20
print(d)

# d[[1, 2]] = 30 # 리스트는 키로 못 씀 원본이 변해서
# print(d)

d[(1, 2)] = 100 # 튜플은 가능 원본이 안 변하니까
print(d)


# 키로 가능한 것 : immutable 타입 (숫자형, 불리언, 문자열, 튜플) -> hashable type
# 키로 안되는 것 : mutable 타입 (리스트, 딕셔너리, 집합) -> unhashable type
# 키는 해시 가능(hashable) + 프로그램 실행 동안 hash값이 변하지 않아야 함



# 딕셔너리가 저장되는 방식
# 1. 딕셔너리 데이터를 저장하기 위한 해시 테이블을 생성함
# 2. hash(key) 함수를 통해 hash값을 얻음
# 3. hash값을 테이블 크기로 압축하여 버킷 인덱스를 계산하고 해시 테이블에 저장함
# 4. key값으로 조회할 때에도 hash(key)로 hash값을 얻어낸 후(동일 hash값) 해당 인덱스로 가서 조회함

print(hash(12345))
print(hash("python"))
print(hash((1, 2)))


# 만약 key에 mutable 타입을 허용했다면?
# 1. hash(key) 함수로 hash값을 얻어 해시 테이블에 저장함
# 2. key 내용이 변경됨
# 3. 다시 hash(바뀐key)를 하면 새로운 hash값이 나옴
# 4. 새 hash값을 이용하여 버킷 인덱스를 계산하고 해시테이블에 조회를 하면 원래 데이터를 찾을 수 없음



